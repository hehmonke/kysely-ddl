import {
  type AnyColumn,
  type BuilderFor,
  ColumnBuilder,
  type ColumnCfg,
  type Fresh,
  freshSpec,
  next,
  type Update,
} from '../columns.ts';

/** The builder of `smallint()`, `integer()` and `bigint()`: the column types that can be identity columns. */
export class IntegerColumnBuilder<T extends ColumnCfg = ColumnCfg> extends ColumnBuilder<T> {
  /** `GENERATED ALWAYS AS IDENTITY`: postgres owns the value, it cannot be inserted. */
  generatedAlwaysAsIdentity(): BuilderFor<Update<T, { notNull: true; hasDefault: true; identity: 'always' }>> {
    return next<T, { notNull: true; hasDefault: true; identity: 'always' }>(this, {
      notNull: true,
      identity: 'always',
    });
  }

  /**
   * `GENERATED BY DEFAULT AS IDENTITY`: the sequence fills the value unless an
   * insert gives one, the way `serial` behaves. For seeds with fixed ids; the
   * sequence does not move past them by itself, `setval` is on the seed.
   */
  generatedByDefaultAsIdentity(): BuilderFor<Update<T, { notNull: true; hasDefault: true; identity: 'byDefault' }>> {
    return next<T, { notNull: true; hasDefault: true; identity: 'byDefault' }>(this, {
      notNull: true,
      identity: 'byDefault',
    });
  }
}

export function integer<N extends string>(name: N): Fresh<'integer', N, number>;
export function integer(): Fresh<'integer', undefined, number>;
export function integer(name?: string): AnyColumn {
  return new IntegerColumnBuilder(freshSpec('integer', 'integer', name));
}
